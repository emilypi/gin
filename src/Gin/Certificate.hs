-- | Axiom policy for the trace (@Certificate@ in the code, @"certificate"@
-- in the JSON): which axioms a proof may depend on.
--
-- Does the proof check? The Lean kernel decides this. The exporter refuses
-- proofs that rely on any axiom beyond Lean's standard three, and @gin@
-- checks that policy again here; @--allow-axiom@ can widen it, but never
-- to an axiom in 'alwaysRejected' or one containing @._native.@.
module Gin.Certificate
  ( CertPolicy (..)
  , defaultPolicy
  , alwaysRejected
  , checkCertificate
  , certificateSpecHash
  , specCanonicalBytes
  ) where

import Data.ByteString (StrictByteString)
import Data.ByteString qualified as BS
import Data.ByteString.Char8 qualified as BS8
import Data.Char (GeneralCategory (..), generalCategory, isSpace)
import Data.Containers.ListUtils (nubOrd)
import Data.Maybe (fromMaybe)
import Data.Set (Set)
import Data.Set qualified as Set
import Data.Text (Text)
import Data.Text qualified as Text
import Data.Text.Encoding qualified as Text
import Gin.Core.Syntax (Certificate (..), SpecDef (..))
import Gin.Error (GinError, Stage (..), ginError)
import Gin.Hash (sha256Hex)

-- | Identity of the specification a trace claims: SHA-256 (lowercase
-- hex) of 'specCanonicalBytes'. Axioms are not part of it. Does the
-- specification say what I want? I review the theorem and its definitions
-- once, then pin this value (@--spec-hash@); any later change to the claim
-- changes it.
certificateSpecHash :: Certificate -> Text
certificateSpecHash = sha256Hex . specCanonicalBytes

-- | The bytes 'certificateSpecHash' digests: the tag @gin-spec/1@, the
-- theorem name, the statement, then each definition's name and body, each
-- field as its UTF-8 byte length in decimal, a colon, and the bytes.
specCanonicalBytes :: Certificate -> StrictByteString
specCanonicalBytes c =
  BS.concat . fmap field $
    ["gin-spec/1", certTheorem c, certStatement c]
      <> concat [[specDefName d, specDefBody d] | d <- certSpecDefs c]
  where
    field t = let b = Text.encodeUtf8 t in BS8.pack (show (BS.length b)) <> ":" <> b

-- | The axioms a trace may name. A policy can only widen what is
-- accepted up to 'alwaysRejected', which no policy admits.
newtype CertPolicy = CertPolicy
  { allowedAxioms :: Set Text
  }
  deriving stock (Eq, Show)

-- | Lean's three standard axioms.
defaultPolicy :: CertPolicy
defaultPolicy = CertPolicy (Set.fromList ["propext", "Classical.choice", "Quot.sound"])

-- | Axioms rejected even when a caller's policy lists them: they make a
-- proof trust something other than the Lean kernel. Any axiom whose name
-- contains @._native.@ (generated by @native_decide@ and @bv_decide@) is
-- rejected as well. Names are compared after normalization, so quoted
-- spellings such as @«sorryAx»@ are rejected too ('checkCertificate').
alwaysRejected :: Set Text
alwaysRejected =
  Set.fromList ["sorryAx", "Lean.ofReduceBool", "Lean.ofReduceNat", "Lean.trustCompiler"]

-- | Reject an empty theorem name or statement, any axiom name that is not
-- valid, any axiom outside the policy in either 'certAxioms' or
-- 'certImplAxioms', and any axiom in 'alwaysRejected' or containing
-- @._native.@. Errors use 'StCertificate' and name every offending axiom.
--
-- Axiom names are compared after normalization: surrounding whitespace is
-- trimmed and Lean's @«»@ quoting is removed from each dot-separated
-- component, so @«sorryAx»@ is @sorryAx@ and @Lean.«ofReduceBool»@ is
-- @Lean.ofReduceBool@. The policy's names are normalized the same way. A
-- quoted component that contains a dot (@«Classical.choice»@) stays quoted:
-- it names a different constant.
--
-- An axiom name is not valid when it is empty after normalization or
-- contains a character in the Unicode categories Cc, Cf, Zl, Zp, Cs, Co or
-- Cn. A name is never allowed when it is a rejected axiom (or contains
-- @._native.@) even after removing every @«@ and @»@, the whitespace
-- around each component and a leading @_root_@, so that no spelling of a
-- rejected axiom gets past a policy.
--
-- A theorem name or statement is empty when it has no character outside
-- whitespace and those categories.
checkCertificate :: CertPolicy -> Certificate -> Either GinError ()
checkCertificate policy c = case problems of
  [] -> Right ()
  ps -> Left (ginError StCertificate (Text.intercalate "; " ps))
  where
    problems =
      ["empty theorem name" | blank (certTheorem c)]
        <> ["empty statement" | blank (certStatement c)]
        <> axiomProblems "axioms" (certAxioms c)
        <> axiomProblems "implAxioms" (certImplAxioms c)
    blank = Text.all (\ch -> isSpace ch || invisible ch)
    allowed = Set.map normalizeName (allowedAxioms policy)
    axiomProblems list axioms =
      [ "axiom " <> shown <> " (in " <> list <> ") " <> reason
      | axiom <- nubOrd axioms
      , Just (shown, reason) <- [verdict axiom]
      ]
    verdict axiom
      | not (validName axiom) =
          Just
            ( showT axiom
            , "is not a valid axiom name: it is empty or contains control or invisible characters"
            )
      | Set.member (looseName axiom) alwaysRejected = Just (axiom, "is never allowed")
      | native (normalizeName axiom) || native (looseName axiom) =
          Just
            (axiom, "comes from native evaluation (native_decide, bv_decide) and is never allowed")
      | Set.member (normalizeName axiom) allowed = Nothing
      | otherwise = Just (axiom, "is not allowed by the axiom policy")
    native = Text.isInfixOf "._native."
    showT = Text.pack . show

-- | Trim surrounding whitespace, then remove Lean's @«»@ quoting from each
-- dot-separated component.
normalizeName :: Text -> Text
normalizeName = Text.intercalate "." . fmap unquote . Text.splitOn "." . Text.strip
  where
    unquote part = fromMaybe part (Text.stripPrefix "«" part >>= Text.stripSuffix "»")

-- | A name to compare with the rejected axioms: every @«@ and @»@ removed,
-- the whitespace around each component trimmed, and a leading @_root_@
-- dropped. Looser than 'normalizeName', so it only ever rejects more.
looseName :: Text -> Text
looseName =
  Text.intercalate "." . dropWhile (== "_root_") . fmap Text.strip . Text.splitOn "."
    . Text.filter (\ch -> ch /= '«' && ch /= '»')

-- | Not empty after normalization, and no control or invisible character.
validName :: Text -> Bool
validName name = not (Text.null (normalizeName name)) && not (Text.any invisible name)

-- | Characters in the Unicode categories Cc, Cf, Zl, Zp, Cs, Co and Cn: they
-- break lines or hide, reorder or disguise text.
invisible :: Char -> Bool
invisible ch =
  generalCategory ch
    `elem` [Control, Format, LineSeparator, ParagraphSeparator, Surrogate, PrivateUse, NotAssigned]
