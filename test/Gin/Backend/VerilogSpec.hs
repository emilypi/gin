-- | Names declared between @lint_off@ and @lint_on@ pragmas, in order.
suppressed :: Text -> [Text]
suppressed = go False . fmap Text.strip . Text.lines
  where
    go inside = \case
      [] -> []
      l : ls
        | l == lintOff -> go True ls
        | l == lintOn -> go False ls
        | inside -> lastWord (Text.dropWhileEnd (`elem` [',', ';']) l) : go inside ls
        | otherwise -> go inside ls

stripPragmas :: Text -> Text
stripPragmas = Text.unlines . filter ((`notElem` [lintOff, lintOn]) . Text.strip) . Text.lines

lintOff, lintOn :: Text
lintOff = "/* verilator lint_off UNUSEDSIGNAL */"
lintOn = "/* verilator lint_on UNUSEDSIGNAL */"

-- | The pragmas before and after a comparison statement.
comparisonOff, comparisonOn :: [Text]
comparisonOff = ["/* verilator lint_off UNSIGNED */", "/* verilator lint_off CMPCONST */"]
comparisonOn = ["/* verilator lint_on CMPCONST */", "/* verilator lint_on UNSIGNED */"]

-- | The statements wrapped one at a time in the comparison pragmas, in
-- order, stripped; 'Nothing' when a comparison pragma is outside such a
-- block.
comparisonWrapped :: Text -> Maybe [Text]
comparisonWrapped = go . fmap Text.strip . Text.lines
  where
    go = \case
      [] -> Just []
      ls
        | Just (l : rest) <- stripPrefix comparisonOff ls
        , Just next <- stripPrefix comparisonOn rest ->
            (l :) <$> go next
      l : ls
        | l `elem` comparisonOff <> comparisonOn -> Nothing
        | otherwise -> go ls

stripComparisonPragmas :: Text -> Text
stripComparisonPragmas =
  Text.unlines . filter ((`notElem` comparisonOff <> comparisonOn) . Text.strip) . Text.lines

-- | Whether a stripped design line assigns an unsigned comparison.
isComparisonAssign :: Text -> Bool
isComparisonAssign l = "assign " `Text.isPrefixOf` l && any (`Text.isInfixOf` l) [" < ", " <= "]

lastWord :: Text -> Text
lastWord = maybe "" snd . unsnoc . Text.words

-- | Port names in declaration order.
portNames :: Text -> [Text]
portNames design =
  [ lastWord (Text.dropWhileEnd (== ',') l)
  | l <- fmap Text.strip (Text.lines design)
  , any (`Text.isPrefixOf` l) ["input ", "output "]
  ]

-- | Lines that are neither comments nor pragmas.
codeLines :: Text -> [Text]
codeLines =
  filter (\l -> not (any (`Text.isPrefixOf` Text.stripStart l) ["//", "/*"])) . Text.lines

-- | Identifier-like words of the code lines (keywords and names).
designWords :: Text -> [Text]
designWords = concatMap (filter (not . Text.null) . Text.split (not . isWordChar)) . codeLines
  where
    isWordChar c = isAsciiLower c || isDigit c || c == '_'

-- | Decimal numbers that are not part of a sized literal, a bit index or
-- a replication count.
unsizedNumbers :: Text -> [Text]
unsizedNumbers = go . Text.unpack
  where
    go = \case
      [] -> []
      s@(c : cs)
        | isAsciiLower c || c == '_' -> go (dropWhile isWordChar s)
        | isDigit c ->
            let (ds, rest) = span isDigit s
             in case rest of
                  '\'' : base : more
                    | base `elem` ("bh" :: String) -> go (dropWhile isLitDigit more)
                  r : _ | r `elem` ("{:]" :: String) -> go rest
                  _ -> Text.pack ds : go rest
        | otherwise -> go cs
    isWordChar x = isAsciiLower x || isDigit x || x == '_'
    isLitDigit x = isHexDigit x || x == 'x'

