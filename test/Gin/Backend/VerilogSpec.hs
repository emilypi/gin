-- Spec

spec :: Spec
spec = do
  describe "backend" $
    it "targets Verilog with the v extension" $ do
      backendTarget verilog `shouldBe` Verilog
      backendFileExt verilog `shouldBe` "v"
  familySpec verilogFlavour
  describe "literals" $ do
    it "prints bits as 1'b0 and 1'b1" $ do
      literal (HLitBit False) `shouldBe` "1'b0"
      literal (HLitBit True) `shouldBe` "1'b1"
    it "prints vectors as sized lowercase hex with ceil(w/4) digits" $ do
      literal (HLitVec 8 15) `shouldBe` "8'h0f"
      literal (HLitVec 1 1) `shouldBe` "1'h1"
      literal (HLitVec 13 0x1abc) `shouldBe` "13'h1abc"
      literal (HLitVec 16 0) `shouldBe` "16'h0000"
    it "prints a width-4096 vector with 1024 digits" $
      literal (HLitVec 4096 (2 ^ (4096 :: Int) - 1))
        `shouldBe` ("4096'h" <> Text.replicate 1024 "f")
    it "reduces out-of-range payloads modulo 2^width" $ do
      hexDigits 4 0x1f `shouldBe` "f"
      hexDigits 8 (-1) `shouldBe` "ff"
      sizedHex 3 8 `shouldBe` "3'h0"
  describe "dialect" $
    it "uses wire, reg and always, never SystemVerilog keywords" $ do
      let ws = concatMap (designWords . backendRender verilog) allNetlists
      filter (`elem` ["logic", "always_ff", "always_comb"]) ws `shouldBe` []
      filter (`elem` ["wire", "reg", "always"]) ws `shouldSatisfy` (not . null)
  describe "reference simulator" $ do
    it "reproduces the shared fixture vectors" $
      forM_ examples $ \(_, m, vs) ->
        referenceVectors m (fmap cycInputs (vecCycles vs)) `shouldBe` vs
    it "matches hand-computed operator results" $
      forM_ handComputed $ \(ty, e, expected) -> do
        let vs = referenceVectors (oneOp ty e) [[VBV 8 0xb6, VBV 8 0x05, VBool True]]
        fmap cycOutputs (vecCycles vs) `shouldBe` [[expected]]

-- | Tests every Verilog-family backend must pass.
familySpec :: Flavour -> Spec
familySpec fl = do
  describe "design files" $ do
    forM_ examples $ \(name, m, _) ->
      it (tag "golden" <> " " <> name <> " matches its golden file") $
        goldenText (golden name) (render m)
    forM_ extraNetlists $ \m ->
      it (tag "golden" <> " " <> moduleName m <> " matches its golden file") $
        goldenText (golden (moduleName m)) (render m)
    it "starts with the header lines as line comments" $
      take 2 (Text.lines (render counterNetlist))
        `shouldBe` ["// generated by gin test fixtures", "// theorem: Counter.counter_correct"]
    it "keeps a header line with line breaks inside one comment" $ do
      let m = counterNetlist {modHeader = ["a\nassign count = 8'h00;", "b\rc\x2028" <> "d"]}
          ls = Text.lines (render m)
      take 2 ls `shouldSatisfy` all ("// " `Text.isPrefixOf`)
      ls !? 2 `shouldBe` Just "module counter ("
      filter (Text.any (`elem` ['\r', '\x2028'])) ls `shouldBe` []
    it "defines exactly one module, named after the netlist" $
      forM_ checkedNetlists $ \m ->
        filter ("module " `Text.isPrefixOf`) (Text.lines (render m))
          `shouldBe` ["module " <> unIdent (modName m) <> " ("]
    it "lists ports in the order clock, reset, inputs, outputs" $
      portNames (render macNetlist) `shouldBe` ["clk", "rst", "x", "y", "acc"]
    it "folds a slice of a constant operand into a literal" $
      render (oneOp (HVec 4) (HSlice 6 3 (vecC 8 0xb6)))
        `shouldSatisfy` Text.isInfixOf "assign n = 4'h6;"
    it "prints a zero-extension to the same width as the plain operand" $
      render (oneOp (HVec 8) (HZext 8 (ref "a"))) `shouldSatisfy` Text.isInfixOf "assign n = a;"
    it "[v-coverage] prints every constant operand as a sized literal" $
      forM_ checkedNetlists $ \m ->
        concatMap unsizedNumbers (codeLines (render m)) `shouldBe` []
    it "[nl-header-spec] the built counter with spec definitions matches its golden file" $
      withSpecCounter (goldenText (golden "counter_spec") . render)
    it "[nl-header-spec] emits every header line, spec lines and hash included, as a comment" $
      withSpecCounter $ \m -> do
        let ls = Text.lines (render m)
        filter ("// spec" `Text.isPrefixOf`) ls `shouldSatisfy` ((> 2) . length)
        take (length (modHeader m)) ls `shouldBe` fmap ("// " <>) (modHeader m)
    itWithTools lintTools "[nl-header-spec] the counter with spec definitions lints clean" $
      withSpecCounter (lintClean fl)
    itWithTools simTools "[nl-header-spec] the counter with spec definitions simulates" $
      withSpecCounter $ \m ->
        simulate fl m counterVectors >>= shouldPass (length (vecCycles counterVectors))
  describe "testbench files" $ do
    forM_ examples $ \(name, m, vs) ->
      it (name <> " testbench matches its golden file") $
        goldenText (golden (name <> "_tb")) (testbench m vs)
    it "never passes a literal to $display" $
      forM_ examples $ \(_, m, vs) ->
        [ l
        | l <- Text.lines (testbench m vs)
        , "$display" `Text.isInfixOf` l
        , "'" `Text.isInfixOf` l
        ]
          `shouldBe` []
    it "drives a missing or ill-typed input value as all X" $ do
      let vs = macVectors {vecCycles = zipWith blank [0 :: Int ..] (vecCycles macVectors)}
          blank i c = if i == 1 then c {cycInputs = [VBool True]} else c
          cycle1 = takeWhile (/= "// cycle 2") (dropWhile (/= "// cycle 1") (strippedLines vs))
          strippedLines = fmap Text.strip . Text.lines . testbench macNetlist
      filter (Text.isSuffixOf "'bx;") cycle1 `shouldBe` ["x = 8'bx;", "y = 8'bx;"]
    it "names its module <name>_tb and uses a 1 ns time unit" $ do
      let ls = Text.lines (testbench counterNetlist counterVectors)
      filter ("`timescale" `Text.isPrefixOf`) ls `shouldBe` ["`timescale 1ns/1ps"]
      filter ("module " `Text.isPrefixOf`) ls `shouldBe` ["module counter_tb;"]
  describe "lint" $
    forM_ examples $ \(name, m, _) ->
      itWithTools lintTools (tag "lint" <> " " <> name <> " passes Verilator -Wall and iverilog") $
        lintClean fl m
  describe "simulation" $ do
    forM_ examples $ \(name, m, vs) ->
      itWithTools simTools (tag "tb-pass" <> " " <> name <> " testbench prints GIN-PASS") $
        simulate fl m vs >>= shouldPass (length (vecCycles vs))
    itWithTools simTools (tag "tb-pass" <> " a testbench with the most cycles allowed passes") $
      simulateWithin slowToolSeconds fl delayNetlist delayVectors >>= shouldPass maxCycles
    it "[v-robust] the most-cycles testbench reaches the payload limit with a generous time bound" $ do
      length (vecCycles delayVectors) `shouldBe` maxCycles
      payloadBits delayVectors `shouldSatisfy` (> maxVectorBits `div` 2)
      payloadBits delayVectors `shouldSatisfy` (<= maxVectorBits)
      slowToolSeconds `shouldSatisfy` (>= 4 * 300)
  describe "failing testbenches" $ do
    itWithTools simTools "[v-tb-fail] corrupted expected values print mismatches and GIN-FAIL" $ do
      let vs = corruptOutput 5 (VBV 8 9) (corruptOutput 3 (VBV 8 7) counterVectors)
      result <- simulate fl counterNetlist vs
      markerLines result
        `shouldBe` [ "GIN-MISMATCH cycle=3 port=count expected=07 got=02"
                   , "GIN-MISMATCH cycle=5 port=count expected=09 got=03"
                   , "GIN-FAIL mismatches=2"
                   ]
    itWithTools simTools "[v-tb-fail] a corrupted Bool expected value fails" $ do
      result <- simulate fl detectorNetlist (corruptOutput 2 (VBool False) detectorVectors)
      markerLines result
        `shouldBe` ["GIN-MISMATCH cycle=2 port=hit expected=0 got=1", "GIN-FAIL mismatches=1"]
    itWithTools simTools "[v-tb-fail] a design that diverges from the vectors fails" $ do
      let buggy = counterNetlist {modDecls = fmap incByTwo (modDecls counterNetlist)}
          incByTwo = \case
            DAssign n (HBin BAdd a _) -> DAssign n (HBin BAdd a (vecC 8 2))
            d -> d
      result <- simulate fl buggy counterVectors
      markerLines result
        `shouldBe` zipWith3
          mismatch
          [1 :: Int ..]
          ["01", "02", "02", "03", "03", "03", "04"]
          ["02", "04", "04", "06", "06", "06", "08"]
        <> ["GIN-FAIL mismatches=7"]
    itWithTools simTools "[v-tb-fail] an undefined output value counts as a mismatch" $ do
      let design = Text.replace "assign count = s;" "assign count = 8'bx;" (render counterNetlist)
      design `shouldNotBe` render counterNetlist
      result <- simulateText fl "counter" design (testbench counterNetlist counterVectors)
      markerLines result
        `shouldBe` zipWith3
          mismatch
          [0 :: Int ..]
          ["00", "01", "02", "02", "03", "03", "03", "04"]
          (repeat "xx")
        <> ["GIN-FAIL mismatches=8"]
    itWithTools simTools "[v-tb-fail] a row missing its expected value counts as a mismatch" $ do
      let vs = counterVectors {vecCycles = zipWith dropAt [0 :: Int ..] (vecCycles counterVectors)}
          dropAt i c = if i == 4 then c {cycOutputs = []} else c
      result <- simulate fl counterNetlist vs
      markerLines result
        `shouldBe` ["GIN-MISMATCH cycle=4 port=count expected=none got=03", "GIN-FAIL mismatches=1"]
    it "[backend-minors] reports nothing extra for well-formed vectors" $
      forM_ examples $ \(_, m, vs) ->
        testbench m vs `shouldNotSatisfy` \t -> any (`Text.isInfixOf` t) ["extra-", "=invalid"]
    itWithTools simTools "[backend-minors] extra input and output values count as mismatches" $ do
      let vs =
            editRow 5 (\c -> c {cycOutputs = cycOutputs c <> [VBV 8 0, VBool True]}) $
              editRow 2 (\c -> c {cycInputs = cycInputs c <> [VBool True]}) counterVectors
      result <- simulate fl counterNetlist vs
      markerLines result
        `shouldBe` [ "GIN-MISMATCH cycle=2 extra-inputs=1"
                   , "GIN-MISMATCH cycle=5 extra-outputs=2"
                   , "GIN-FAIL mismatches=2"
                   ]
    itWithTools simTools "[backend-minors] an ill-typed value of an unread input is a mismatch" $ do
      let good = referenceVectors spareNetlist [spareRow k | k <- [0 .. 5]]
          bad = editRow 3 (\c -> c {cycInputs = zipWith badB [0 :: Int ..] (cycInputs c)}) good
          badB i v = if i == 1 then VBV 8 1 else v
      simulate fl spareNetlist good >>= shouldPass 6
      result <- simulate fl spareNetlist bad
      markerLines result
        `shouldBe` ["GIN-MISMATCH cycle=3 port=b input=invalid", "GIN-FAIL mismatches=1"]
  describe "operator coverage" $ do
    itWithTools lintTools "[v-coverage] a netlist using every operator lints clean" $
      lintClean fl allOpsNetlist
    itWithTools simTools "[v-coverage] a netlist using every operator simulates correctly" $
      simulate fl allOpsNetlist allOpsVectors >>= shouldPass (length (vecCycles allOpsVectors))
  describe "extreme widths" $ do
    itWithTools lintTools "[v-wide] width-4096 and width-1 vectors lint clean" $
      lintClean fl wideNetlist
    itWithTools simTools "[v-wide] width-4096 and width-1 vectors pass under iverilog" $
      simulate fl wideNetlist wideVectors >>= shouldPass (length (vecCycles wideVectors))
  describe "lint suppressions" $ do
    itWithTools lintTools "[v-unused] a register-free module lints clean" $
      lintClean fl combNetlist
    it "[v-unused] a register-free module suppresses exactly clk and rst" $
      suppressed (render combNetlist) `shouldBe` ["clk", "rst"]
    itWithTools lintTools "[v-unused] unread and partly read signals lint clean" $
      lintClean fl spareNetlist
    it "[v-unused] suppresses exactly the unread input and the partly read signals" $
      suppressed (render spareNetlist) `shouldBe` ["b", "c", "t"]
    it "[v-unused] suppresses nothing in the shared fixtures" $
      forM_ examples $ \(_, m, _) -> suppressed (render m) `shouldBe` []
    itWithTools ["verilator"] "[v-unused] without the pragmas Verilator warns about those signals" $
      forM_ [combNetlist, spareNetlist] $ \m -> do
        warnings <- verilatorWarnings fl m (stripPragmas (render m))
        sort warnings `shouldBe` sort (fmap ("UNUSEDSIGNAL",) (suppressed (render m)))
    itWithTools simTools "[v-unused] a register-free module simulates correctly" $
      simulate fl combNetlist combVectors >>= shouldPass (length (vecCycles combVectors))
  describe "comparisons a constant operand decides" $ do
    it "print as their one-bit result, other comparisons as comparisons" $ do
      let isComparison l = any (\c -> assignPrefix c `Text.isPrefixOf` l) allComparisons
      filter isComparison (fmap Text.strip (Text.lines (render decidedNetlist)))
        `shouldBe` fmap foldedLine decidedComparisons <> fmap comparisonLine liveComparisons
    itWithTools lintTools (tag "lint" <> " at widths 1, 8 and 4096 they lint clean") $
      lintClean fl decidedNetlist
    itWithTools ["verilator"] (tag "lint" <> " printed as comparisons, Verilator rejects them") $ do
      let unfold d = Text.replace (foldedLine d) (comparisonLine (dcComparison d))
          design = foldr unfold (render decidedNetlist) decidedComparisons
      design `shouldNotBe` render decidedNetlist
      warnings <- verilatorWarningLines fl decidedNetlist design
      sort warnings
        `shouldBe` sort [(dcWarning d, comparisonLine (dcComparison d)) | d <- decidedComparisons]
    it "[v-unused] suppresses exactly the signals that only those comparisons read" $
      suppressed (render decidedNetlist) `shouldBe` ["a1", "a8", "a4096", "r", "s"]
    itWithTools simTools (tag "tb-pass" <> " they simulate as the comparisons they replace") $
      simulate fl decidedNetlist decidedVectors >>= shouldPass (length (vecCycles decidedVectors))
  describe "comparisons of nets Verilator proves constant" $ do
    it "wrap each comparison statement, and nothing else, in UNSIGNED and CMPCONST pragmas" $ do
      comparisonWrapped (render chainNetlist)
        `shouldBe` Just (fmap (comparisonLine . fst) chainComparisons)
      forM_ checkedNetlists $ \m ->
        comparisonWrapped (render m)
          `shouldBe` Just (filter isComparisonAssign (fmap Text.strip (Text.lines (render m))))
    itWithTools lintTools (tag "lint" <> " at widths 1, 8 and 4096 they lint clean") $
      lintClean fl chainNetlist
    itWithTools ["verilator"] (tag "lint" <> " without the pragmas Verilator rejects each one") $ do
      let design = stripComparisonPragmas (render chainNetlist)
      design `shouldNotBe` render chainNetlist
      warnings <- verilatorWarningLines fl chainNetlist design
      sort warnings `shouldBe` sort [(code, comparisonLine c) | (c, code) <- chainComparisons]
    itWithTools simTools (tag "tb-pass" <> " they simulate correctly") $
      simulate fl chainNetlist chainVectors >>= shouldPass (length (vecCycles chainVectors))
    itWithTools lintTools "[v-coverage] nets holding 0, 1 or all ones in any operator lint clean" $
      lintClean fl constantNetsNetlist
    itWithTools simTools "[v-coverage] nets holding 0, 1 or all ones in any operator simulate" $
      simulate fl constantNetsNetlist constantNetsVectors
        >>= shouldPass (length (vecCycles constantNetsVectors))
  where
    tag t = "[" <> flTag fl <> "-" <> t <> "]"
    b = flBackend fl
    render = backendRender b
    testbench = backendTestbench b
    golden name = flGoldenDir fl </> name <> "." <> backendFileExt b
    mismatch t expected got =
      Text.concat
        ["GIN-MISMATCH cycle=", Text.pack (show t), " port=count expected=", expected, " got=", got]

