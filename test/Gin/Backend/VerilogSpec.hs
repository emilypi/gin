moduleName :: Module -> FilePath
moduleName = Text.unpack . unIdent . modName

mkModule :: Text -> [Net] -> [Output] -> [Decl] -> Module
mkModule name ins outs decls =
  Module
    { modName = Ident name
    , modHeader = ["generated by the backend test suite"]
    , modClock = Ident "clk"
    , modReset = Ident "rst"
    , modInputs = ins
    , modOutputs = outs
    , modDecls = decls
    }

net :: Text -> HwType -> Net
net = Net . Ident

ref :: Text -> Operand
ref = ORef . Ident

vecC :: Natural -> Integer -> Operand
vecC w = OConst . HLitVec w

bitC :: Bool -> Operand
bitC = OConst . HLitBit

-- | An output port @o_<net>@ for every declared net.
observeAll :: [Decl] -> [Output]
observeAll decls =
  [ Output (Net (Ident ("o_" <> unIdent (netName n))) (netType n)) (ORef (netName n))
  | n <- fmap declNet decls
  ]

-- | Every 'HExpr', 'BinOp' and 'UnOp' constructor, with a constant in
-- every operand position the netlist invariants allow, on HBit and HVec
-- operands; registers with Bool, vector and constant next values; and
-- outputs driven by constants and by an input. Every net is an output.
allOpsNetlist :: Module
allOpsNetlist =
  mkModule
    "allops"
    [net "a" v8, net "b" v8, net "p" HBit, net "q" HBit]
    ( observeAll decls
        <> [ Output (net "o_k8" v8) (vecC 8 0x3c)
           , Output (net "o_kb" HBit) (bitC False)
           , Output (net "o_q" HBit) (ref "q")
           ]
    )
    decls
  where
    v8 = HVec 8
    decls = registers <> zipWith numbered [0 :: Int ..] exprs
    numbered i (ty, e) = DAssign (net ("n" <> Text.pack (show i)) ty) e
    registers =
      [ DReg (net "acc" v8) (HLitVec 8 0xa5) (ref "acc_next")
      , DAssign (net "acc_next" v8) (HBin BAdd (ref "acc") (ref "a"))
      , DAssign (net "acc_hi" (HVec 3)) (HSlice 7 5 (ref "acc"))
      , DReg (net "flag" HBit) (HLitBit True) (ref "p")
      , DReg (net "held" (HVec 4)) (HLitVec 4 3) (vecC 4 9)
      ]
    resultTy op = if op `elem` [BEq, BUlt, BUle] then HBit else v8
    exprs =
      [ (v8, HOperand (ref "a"))
      , (v8, HOperand (vecC 8 0x5a))
      , (HBit, HOperand (bitC True))
      , (v8, HUn UNot (ref "a"))
      , (v8, HUn UNot (vecC 8 0x0f))
      , (HBit, HUn UNot (ref "p"))
      , (HBit, HUn UNot (bitC False))
      , (v8, HUn UNeg (ref "a"))
      , (v8, HUn UNeg (vecC 8 1))
      ]
        <> concat
          [ [ (resultTy op, HBin op (ref "a") (ref "b"))
            , (resultTy op, HBin op (vecC 8 0xc3) (ref "b"))
            , (resultTy op, HBin op (ref "a") (vecC 8 0x3c))
            ]
          | op <- [minBound .. maxBound]
          ]
        <> concat
          [ [ (HBit, HBin op (ref "p") (ref "q"))
            , (HBit, HBin op (bitC True) (ref "q"))
            , (HBit, HBin op (ref "p") (bitC False))
            ]
          | op <- [BAnd, BOr, BXor, BEq]
          ]
        <> [ (v8, HMux (ref "p") (ref "a") (ref "b"))
           , (v8, HMux (bitC True) (ref "a") (ref "b"))
           , (v8, HMux (ref "p") (vecC 8 0x11) (ref "b"))
           , (v8, HMux (ref "p") (ref "a") (vecC 8 0x22))
           , (HBit, HMux (ref "q") (ref "p") (bitC True))
           , (v8, HShl 0 (ref "a"))
           , (v8, HShl 3 (ref "a"))
           , (v8, HShl 7 (ref "a"))
           , (v8, HShl 2 (vecC 8 0x81))
           , (v8, HLshr 0 (ref "a"))
           , (v8, HLshr 3 (ref "a"))
           , (v8, HLshr 7 (ref "a"))
           , (v8, HLshr 5 (vecC 8 0xf0))
           , (HVec 4, HSlice 7 4 (ref "a"))
           , (HVec 1, HSlice 0 0 (ref "b"))
           , (v8, HSlice 7 0 (ref "a"))
           , (HVec 16, HConcat (ref "a") (ref "b"))
           , (HVec 12, HConcat (vecC 4 0xa) (ref "b"))
           , (HVec 9, HConcat (ref "a") (vecC 1 1))
           , (HVec 16, HZext 16 (ref "a"))
           , (v8, HZext 8 (ref "b"))
           , (HVec 12, HZext 12 (vecC 8 0xff))
           , (HVec 1, HBitToVec (ref "p"))
           , (HVec 1, HBitToVec (bitC True))
           ]

-- | Edge values first, then pseudo-random rows.
allOpsVectors :: Vectors
allOpsVectors = referenceVectors allOpsNetlist (edges <> fmap row (take 28 (pseudoRandom 7)))
  where
    edges =
      [ [VBV 8 0, VBV 8 0, VBool False, VBool False]
      , [VBV 8 255, VBV 8 255, VBool True, VBool True]
      , [VBV 8 255, VBV 8 1, VBool True, VBool False]
      , [VBV 8 128, VBV 8 128, VBool False, VBool True]
      ]
    row r =
      [ VBV 8 (r `mod` 256)
      , VBV 8 ((r `shiftR` 8) `mod` 256)
      , VBool (odd (r `shiftR` 16))
      , VBool (odd (r `shiftR` 17))
      ]

pseudoRandom :: Integer -> [Integer]
pseudoRandom = fmap (`shiftR` 8) . drop 1 . iterate lcg
  where
    lcg x = (x * 1103515245 + 12345) `mod` 2147483648

-- | A width-4096 input, register and outputs next to width-1 vectors.
wideNetlist :: Module
wideNetlist =
  mkModule "wide" [net "a" w, net "s" (HVec 1), net "p" HBit] (observeAll decls) decls
  where
    w = HVec 4096
    decls =
      [ DReg (net "big" w) (HLitVec 4096 widePattern) (ref "a")
      , DAssign (net "mixed" w) (HBin BXor (ref "big") (vecC 4096 (widePattern `shiftR` 4)))
      , DAssign (net "total" w) (HBin BAdd (ref "a") (vecC 4096 (2 ^ (4096 :: Int) - 1)))
      , DAssign (net "same" HBit) (HBin BEq (ref "a") (vecC 4096 widePattern))
      , DAssign (net "s_inc" (HVec 1)) (HBin BAdd (ref "s") (vecC 1 1))
      , DAssign (net "s_wide" w) (HZext 4096 (ref "s"))
      , DAssign (net "p_vec" (HVec 1)) (HBitToVec (ref "p"))
      , DAssign (net "top" (HVec 8)) (HSlice 4095 4088 (ref "total"))
      ]

widePattern :: Integer
widePattern = foldl (\acc _ -> acc * 2 ^ (64 :: Int) + 0xfedcba9876543210) 0 [1 .. 64 :: Int]

wideVectors :: Vectors
wideVectors =
  referenceVectors
    wideNetlist
    [ [VBV 4096 0, VBV 1 0, VBool False]
    , [VBV 4096 (2 ^ (4096 :: Int) - 1), VBV 1 1, VBool True]
    , [VBV 4096 widePattern, VBV 1 1, VBool False]
    , [VBV 4096 12345, VBV 1 0, VBool True]
    ]

-- | No registers: the clock and reset are unread.
combNetlist :: Module
combNetlist =
  mkModule
    "comb"
    [net "a" (HVec 4)]
    [Output (net "y" (HVec 4)) (ref "na")]
    [DAssign (net "na" (HVec 4)) (HUn UNot (ref "a"))]

combVectors :: Vectors
combVectors = referenceVectors combNetlist [[VBV 4 x] | x <- [0, 5, 15, 10]]

-- | A one-cycle delay of a Bool input.
delayNetlist :: Module
delayNetlist =
  mkModule
    "delay"
    [net "a" HBit]
    [Output (net "y" HBit) (ref "q")]
    [DReg (net "q" HBit) (HLitBit False) (ref "a")]

-- | 'maxCycles' cycles (200000 payload bits, within 'Gin.Limits.maxVectorBits').
delayVectors :: Vectors
delayVectors =
  referenceVectors delayNetlist [[VBool (odd r)] | r <- take maxCycles (pseudoRandom 3)]

-- | Input @b@ is unread, input @c@ and net @t@ are partly read; input
-- @d@ is read completely, but only through two slices.
spareNetlist :: Module
spareNetlist =
  mkModule
    "spare"
    [net "a" v8, net "b" HBit, net "c" v8, net "d" v8]
    [ Output (net "o_c" (HVec 4)) (ref "c_lo")
    , Output (net "o_dh" (HVec 4)) (ref "d_hi")
    , Output (net "o_dl" (HVec 4)) (ref "d_lo")
    , Output (net "o_m" (HVec 1)) (ref "t_msb")
    ]
    [ DAssign (net "c_lo" (HVec 4)) (HSlice 3 0 (ref "c"))
    , DAssign (net "d_hi" (HVec 4)) (HSlice 7 4 (ref "d"))
    , DAssign (net "d_lo" (HVec 4)) (HSlice 3 0 (ref "d"))
    , DReg (net "q" v8) (HLitVec 8 0) (ref "a")
    , DAssign (net "t" v8) (HBin BXor (ref "q") (ref "a"))
    , DAssign (net "t_msb" (HVec 1)) (HSlice 7 7 (ref "t"))
    ]
  where
    v8 = HVec 8

