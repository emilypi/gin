-- | Tests for the Verilog-2005 backend.
--
-- The tool-checked tests are shared with "Gin.Backend.SystemVerilogSpec"
-- through 'familySpec', which runs them against one 'Flavour' (backend,
-- language flags, golden directory). Tool runs follow the commands in
-- the backend interface: a private temporary directory holding
-- @<module>.<ext>@ and @<module>_tb.<ext>@.
--
-- Expected outputs for netlists other than the shared fixtures come from
-- 'referenceVectors', a cycle simulator written directly from the tables
-- in @docs/semantics.md@ and checked here against hand-computed values
-- and the fixtures' vectors.
module Gin.Backend.VerilogSpec
  ( spec
    -- * Shared with the SystemVerilog suite
  , Flavour (..)
  , familySpec
  , designWords
  , allNetlists
  ) where

