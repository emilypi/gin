-- Flavours

-- | One member of the Verilog family under test.
data Flavour = Flavour
  { flBackend :: Backend
  , flTag :: String
  -- ^ Prefix of the target-specific test tags: @v@ or @sv@.
  , flGoldenDir :: FilePath
  -- ^ Directory under @test/golden@.
  , flIcarusStd :: String
  -- ^ @iverilog@ language flag.
  , flVerilatorLanguage :: String
  -- ^ Verilator @--default-language@ value.
  }

verilogFlavour :: Flavour
verilogFlavour =
  Flavour
    { flBackend = verilog
    , flTag = "v"
    , flGoldenDir = "verilog"
    , flIcarusStd = "-g2005"
    , flVerilatorLanguage = "1364-2005"
    }

