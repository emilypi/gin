-- Tool runs

lintTools, simTools :: [String]
lintTools = ["verilator", "iverilog"]
simTools = ["iverilog", "vvp"]

designFile, benchFile :: Flavour -> Text -> FilePath
designFile fl name = Text.unpack name <> "." <> backendFileExt (flBackend fl)
benchFile fl name = Text.unpack name <> "_tb." <> backendFileExt (flBackend fl)

writeUtf8 :: FilePath -> Text -> IO ()
writeUtf8 path = ByteString.writeFile path . Text.encodeUtf8

verilatorArgs :: Flavour -> FilePath -> [String]
verilatorArgs fl file = ["--lint-only", "-Wall", "--default-language", flVerilatorLanguage fl, file]

-- | Both lint commands exit 0; Verilator prints no warning or error line
-- (only its statistics report) and iverilog prints nothing.
lintClean :: Flavour -> Module -> Expectation
lintClean fl m = withTempDir $ \dir -> do
  let file = designFile fl (unIdent (modName m))
  writeUtf8 (dir </> file) (backendRender (flBackend fl) m)
  (code, out, err) <- runTool dir "verilator" (verilatorArgs fl file)
  (code, filter ("%" `Text.isPrefixOf`) (Text.lines (out <> err))) `shouldBe` (ExitSuccess, [])
  icarusRun <- runTool dir "iverilog" [flIcarusStd fl, "-o", "/dev/null", file]
  combined icarusRun `shouldBe` (ExitSuccess, "")

-- | Verilator @-Wall@ warnings on a design text, as (code, signal) pairs:
-- the signal is the first quoted name in the message.
verilatorWarnings :: Flavour -> Module -> Text -> IO [(Text, Text)]
verilatorWarnings fl m design = do
  diagnostics <- verilatorDiagnostics fl m design
  pure
    [ (code, Text.takeWhile (/= '\'') (Text.drop 1 (snd (Text.breakOn "'" msg))))
    | (code, _, msg) <- diagnostics
    ]

-- | Verilator @-Wall@ warnings on a design text, as (code, source line)
-- pairs: the source line is the stripped design line the warning points
-- at, or empty when the warning names no line.
verilatorWarningLines :: Flavour -> Module -> Text -> IO [(Text, Text)]
verilatorWarningLines fl m design = do
  diagnostics <- verilatorDiagnostics fl m design
  pure
    [ (code, maybe "" Text.strip (lineNo >>= \n -> Text.lines design !? (n - 1)))
    | (code, lineNo, _) <- diagnostics
    ]

-- | Every Verilator @-Wall@ warning on a design text, as its code, the
-- line it points at (when it names one) and its message.
verilatorDiagnostics :: Flavour -> Module -> Text -> IO [(Text, Maybe Int, Text)]
verilatorDiagnostics fl m design = withTempDir $ \dir -> do
  let file = designFile fl (unIdent (modName m))
  writeUtf8 (dir </> file) design
  (exit, out, err) <- runTool dir "verilator" (verilatorArgs fl file)
  let found =
        [ diagnostic code (Text.drop 1 body)
        | l <- Text.lines (out <> err)
        , Just rest <- [Text.stripPrefix "%Warning-" l]
        , let (code, body) = Text.breakOn ":" rest
        ]
  -- a run that failed without a single warning (a timeout, a crash) is a
  -- tool failure, not a clean design: report it instead of returning none
  when (exit /= ExitSuccess && null found) $
    expectationFailure
      ("verilator failed without warnings: " <> show exit <> "\n" <> Text.unpack (out <> err))
  pure found
  where
    -- @<file>:<line>:<column>: <message>@
    diagnostic code body = case Text.splitOn ":" body of
      _ : lineText : _ : msg
        | Right (n, "") <- TextRead.decimal lineText -> (code, Just n, Text.intercalate ":" msg)
      _ -> (code, Nothing, body)

-- | Compile the design and testbench with iverilog, which must be silent,
-- and run the result under vvp.
simulate :: Flavour -> Module -> Vectors -> IO (ExitCode, Text, Text)
simulate fl m vs =
  simulateText fl (unIdent (modName m)) (backendRender b m) (backendTestbench b m vs)
  where
    b = flBackend fl

simulateText :: Flavour -> Text -> Text -> Text -> IO (ExitCode, Text, Text)
simulateText = simulateTextWith runTool

-- | 'simulate' with a per-tool time limit of the given number of seconds
-- instead of the usual 300 s.
--
-- The testbench with the most cycles allowed compiles and runs in about
-- 7 s on an idle machine, but under heavy load (many simulators and
-- compilers sharing the host) it has hit the 300 s limit, which made the
-- test fail without any fault in the testbench. It gets a limit long
-- enough for a loaded machine; a real hang still fails, only later.
simulateWithin :: Int -> Flavour -> Module -> Vectors -> IO (ExitCode, Text, Text)
simulateWithin seconds fl m vs =
  simulateTextWith
    (runToolWithin seconds)
    fl
    (unIdent (modName m))
    (backendRender b m)
    (backendTestbench b m vs)
  where
    b = flBackend fl

-- | The per-tool time limit, in seconds, of the slowest simulation test.
slowToolSeconds :: Int
slowToolSeconds = 1800

simulateTextWith
  :: (FilePath -> String -> [String] -> IO (ExitCode, Text, Text))
  -> Flavour
  -> Text
  -> Text
  -> Text
  -> IO (ExitCode, Text, Text)
simulateTextWith run fl name design bench = withTempDir $ \dir -> do
  writeUtf8 (dir </> designFile fl name) design
  writeUtf8 (dir </> benchFile fl name) bench
  compiled <-
    run dir "iverilog" [flIcarusStd fl, "-o", "tb.vvp", designFile fl name, benchFile fl name]
  combined compiled `shouldBe` (ExitSuccess, "")
  run dir "vvp" ["-n", "tb.vvp"]

-- | Run a tool (no shell) in a working directory with a limit of the given
-- number of seconds; on timeout the tool is killed and the result is exit
-- code 124 with empty output.
runToolWithin :: Int -> FilePath -> String -> [String] -> IO (ExitCode, Text, Text)
runToolWithin seconds cwd' exe args =
  timeout (seconds * 1000000) (readCreateProcessWithExitCode (proc exe args) {cwd = Just cwd'} "")
    >>= \case
      Just (code, out, err) -> pure (code, Text.pack out, Text.pack err)
      Nothing -> pure (ExitFailure 124, "", Text.pack ("timeout: " <> exe))

-- | Payload bits of a vector set: cycles times the widths of all ports.
payloadBits :: Vectors -> Integer
payloadBits vs =
  fromIntegral (length (vecCycles vs))
    * sum [toInteger (width (portTy p)) | p <- vecInputs vs <> vecOutputs vs]
  where
    width = \case
      TBitVec w -> w
      _ -> 1

-- | Change cycle @t@ of a vector set.
editRow :: Int -> (Cycle -> Cycle) -> Vectors -> Vectors
editRow t f vs = vs {vecCycles = zipWith edit [0 :: Int ..] (vecCycles vs)}
  where
    edit i c = if i == t then f c else c

-- | Row @k@ of inputs for 'spareNetlist'.
spareRow :: Integer -> [Value]
spareRow k = [VBV 8 (k * 37 `mod` 256), VBool (odd k), VBV 8 (k * 11), VBV 8 (255 - k)]

combined :: (ExitCode, Text, Text) -> (ExitCode, Text)
combined (code, out, err) = (code, out <> err)

-- | The pass rule of @docs/semantics.md@: exit 0, exactly one
-- @GIN-PASS cycles=<n>@ line, and no failure or mismatch line.
shouldPass :: Int -> (ExitCode, Text, Text) -> Expectation
shouldPass n result@(code, _, _) = do
  markerLines result `shouldBe` [passMarker <> " cycles=" <> Text.pack (show n)]
  code `shouldBe` ExitSuccess

-- | Standard-output lines that carry a protocol marker.
markerLines :: (ExitCode, Text, Text) -> [Text]
markerLines (_, out, _) =
