-- | Replace the first expected output of cycle @t@.
corruptOutput :: Int -> Value -> Vectors -> Vectors
corruptOutput t v vs = vs {vecCycles = zipWith corrupt [0 ..] (vecCycles vs)}
  where
    corrupt i c = if i == t then c {cycOutputs = v : drop 1 (cycOutputs c)} else c

