-- Reference simulator

-- | The vectors a netlist produces for the given input rows, following
-- the cycle semantics and primitive table of @docs/semantics.md@.
referenceVectors :: Module -> [[Value]] -> Vectors
referenceVectors m rows =
  Vectors
    { vecTop = unIdent (modName m)
    , vecInputs = fmap port (modInputs m)
    , vecOutputs = fmap (port . outNet) (modOutputs m)
    , vecCycles = snd (mapAccumL step initialRegs rows)
    }
  where
    port n = Port (unIdent (netName n)) (portTy (netType n))
    portTy = \case
      HBit -> TBool
      HVec w -> TBitVec w
    widths = moduleNets m
    initialRegs = Map.fromList [(netName n, litBits r) | DReg n r _ <- modDecls m]
    step regs row = (next, Cycle row outs)
      where
        -- Lazy in the values, so combinational nets may appear in any order.
        env =
          Map.unions
            [ Map.fromList (zip (fmap netName (modInputs m)) (fmap valueBits row))
            , regs
            , Map.fromList [(netName n, evalExpr e) | DAssign n e <- modDecls m]
            ]
        next = Map.fromList [(netName n, val o) | DReg n _ o <- modDecls m]
        outs = [toValue (netType n) (val o) | Output n o <- modOutputs m]
        val = \case
          ORef i -> Map.findWithDefault 0 i env
          OConst l -> litBits l
        width = \case
          ORef i -> maybe 1 hwWidth (Map.lookup i widths)
          OConst l -> hwWidth (hlitType l)
        evalExpr = \case
          HOperand o -> val o
          HUn UNot o -> wrap (width o) (complement (val o))
          HUn UNeg o -> wrap (width o) (negate (val o))
          HBin op x y -> binary op (width x) (val x) (val y)
          HMux c t e -> if val c /= 0 then val t else val e
          HShl k o -> wrap (width o) (val o `shiftL` fromIntegral k)
          HLshr k o -> val o `shiftR` fromIntegral k
          HSlice hi lo o -> wrap (hi - lo + 1) (val o `shiftR` fromIntegral lo)
          HConcat x y -> (val x `shiftL` fromIntegral (width y)) .|. val y
          HZext _ o -> val o
          HBitToVec o -> val o
    binary op w x y = case op of
      BAnd -> x .&. y
      BOr -> x .|. y
      BXor -> x `xor` y
      BAdd -> wrap w (x + y)
      BSub -> wrap w (x - y)
      BMul -> wrap w (x * y)
      BEq -> fromBool (x == y)
      BUlt -> fromBool (x < y)
      BUle -> fromBool (x <= y)
    fromBool c = if c then 1 else 0
    wrap :: Natural -> Integer -> Integer
    wrap w x = x `mod` (2 ^ w)
    litBits = \case
      HLitBit c -> fromBool c
      HLitVec _ x -> x
    valueBits = \case
      VBool c -> fromBool c
      VBV _ x -> x
      VTuple _ -> 0
    toValue ty x = case ty of
      HBit -> VBool (x /= 0)
      HVec w -> VBV w x

-- | A module computing one operator over inputs @a@, @b@ (8 bits) and
-- @p@ (Bool), output @y@.
oneOp :: HwType -> HExpr -> Module
oneOp ty e =
  mkModule
    "op"
    [net "a" (HVec 8), net "b" (HVec 8), net "p" HBit]
    [Output (net "y" ty) (ref "n")]
    [DAssign (net "n" ty) e]

-- | Operator results for a = 0xb6, b = 0x05, p = true, computed by hand.
handComputed :: [(HwType, HExpr, Value)]
handComputed =
