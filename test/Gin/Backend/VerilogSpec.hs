  , (HVec 8, HBin BOr (ref "a") (ref "b"), VBV 8 0xb7)
  , (HVec 8, HBin BXor (ref "a") (ref "b"), VBV 8 0xb3)
  , (HVec 8, HBin BAdd (ref "a") (vecC 8 0x60), VBV 8 0x16)
  , (HVec 8, HBin BSub (ref "b") (ref "a"), VBV 8 0x4f)
  , (HVec 8, HBin BMul (ref "a") (ref "b"), VBV 8 0x8e)
