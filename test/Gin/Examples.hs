-- | Hand-written example circuits at every pipeline level, shared by all
-- component test suites: I keep them here so each package can be tested in
-- isolation.
--
-- These mirror, but are not byte-identical to, what the Lean exporter emits
-- for the same circuits.
module Gin.Examples
  ( -- * Shared
    sysDomain
  , testCertificate
  , bv
  , sig
    -- * counter: 8-bit enable counter, output is the current count
  , counterProgram
  , counterNormal
  , counterNetlist
  , counterVectors
    -- * mac: 8x8 -> 16 multiply-accumulate, output is the accumulator
  , macProgram
  , macNormal
  , macNetlist
  , macVectors
    -- * detector: overlapping "101" sequence detector (Mealy output)
  , detectorProgram
  , detectorNormal
  , detectorNetlist
  , detectorVectors
  ) where

import Data.Text (Text)
import Gin.Core.Normal
import Gin.Core.Syntax
import Gin.Netlist.Types
import Gin.Vectors (Cycle (..), Vectors (..))
import Numeric.Natural (Natural)

sysDomain :: Domain
sysDomain = Domain "System" 10000

testCertificate :: Text -> Certificate
testCertificate thm =
  Certificate
    { certTheorem = thm
    , certStatement = "(hand-written test fixture)"
    , certAxioms = ["propext"]
    , certImplAxioms = []
    , certSpecDefs = []
    }

producer :: Producer
producer = Producer "gin-test-examples" "n/a"

bv :: Natural -> Ty
bv = TBitVec

sig :: Ty -> Ty
sig = TSignal "System"

prim :: PrimOp -> [Ty] -> Ty -> Expr
prim op args res = EPrim op (tFuns args res)

v :: Text -> Expr
v = EVar . Name

----------------------------------------------------------------------
-- counter

-- > counter en = mealy (\s e -> (if e then s + 1 else s, s)) 0 en
counterProgram :: Program
counterProgram =
  Program
    { progProducer = producer
    , progTop =
        TopEntity
          { topName = "counter"
          , topDomain = sysDomain
          , topInputs = [Port "en" TBool]
          , topOutputs = [Port "count" (bv 8)]
          , topDef = "Counter.counter"
          }
    , progDefs = [Def "Counter.counter" (TFun (sig TBool) (sig (bv 8))) body]
    , progCertificate = testCertificate "Counter.counter_correct"
    }
  where
    body =
      ELam [("en", sig TBool)] $
        EApp (prim (SigMealy (VBV 8 0)) [stepTy, sig TBool] (sig (bv 8))) [step, v "en"]
    stepTy = tFuns [bv 8, TBool] (TProd [bv 8, bv 8])
    step =
      ELam [("s", bv 8), ("e", TBool)] $
        ETuple
          [ EIf (v "e") (EApp (prim BvAdd [bv 8, bv 8] (bv 8)) [v "s", ELit (VBV 8 1)]) (v "s")
          , v "s"
          ]

counterNormal :: NModule
counterNormal =
  NModule
    { nmName = "counter"
    , nmDomain = sysDomain
    , nmInputs = [("en", TBool)]
    , nmOutputs = [NOutput "count" (bv 8) (AVar "s")]
    , nmBinds =
        [ NBind "s" (bv 8) (NReg (VBV 8 0) (AVar "s_next"))
        , NBind "inc" (bv 8) (NPrim BvAdd [AVar "s", ALit (VBV 8 1)])
        , NBind "s_next" (bv 8) (NMux (AVar "en") (AVar "inc") (AVar "s"))
        ]
    , nmCertificate = testCertificate "Counter.counter_correct"
    }

