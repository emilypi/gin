-- detector

-- > detector b = mealy step 0 b where
-- >   step s i | s == 0    = (if i then 1 else 0, false)
-- >            | s == 1    = (if i then 1 else 2, false)
-- >            | otherwise = (if i then 1 else 0, i)
detectorProgram :: Program
detectorProgram =
  Program
    { progProducer = producer
    , progTop =
        TopEntity
          { topName = "detector"
          , topDomain = sysDomain
          , topInputs = [Port "b" TBool]
          , topOutputs = [Port "hit" TBool]
          , topDef = "Detector.detector"
          }
    , progDefs =
        [ Def "Detector.step" stepTy step
        , Def "Detector.detector" (TFun (sig TBool) (sig TBool)) body
        ]
    , progCertificate = testCertificate "Detector.detector_correct"
    }
  where
    stepTy = tFuns [bv 2, TBool] (TProd [bv 2, TBool])
    body =
      ELam [("b", sig TBool)] $
        EApp
          (prim (SigMealy (VBV 2 0)) [stepTy, sig TBool] (sig TBool))
          [EGlobal "Detector.step", v "b"]
    lit2 = ELit . VBV 2
    isState n = EApp (prim BvEq [bv 2, bv 2] TBool) [v "s", lit2 n]
    pick a b = EIf (v "i") (lit2 a) (lit2 b)
    step =
      ELam [("s", bv 2), ("i", TBool)] $
        EIf
          (isState 0)
          (ETuple [pick 1 0, ELit (VBool False)])
          ( EIf
              (isState 1)
              (ETuple [pick 1 2, ELit (VBool False)])
              (ETuple [pick 1 0, v "i"])
          )

-- | One mux per scalar component of the step function's result.
detectorNormal :: NModule
detectorNormal =
  NModule
    { nmName = "detector"
    , nmDomain = sysDomain
    , nmInputs = [("b", TBool)]
    , nmOutputs = [NOutput "hit" TBool (AVar "o_hit")]
    , nmBinds =
        [ NBind "s" (bv 2) (NReg (VBV 2 0) (AVar "s_next"))
        , NBind "is0" TBool (NPrim BvEq [AVar "s", ALit (VBV 2 0)])
        , NBind "is1" TBool (NPrim BvEq [AVar "s", ALit (VBV 2 1)])
        , NBind "pick10" (bv 2) (NMux (AVar "b") (ALit (VBV 2 1)) (ALit (VBV 2 0)))
        , NBind "pick12" (bv 2) (NMux (AVar "b") (ALit (VBV 2 1)) (ALit (VBV 2 2)))
        , NBind "s_inner" (bv 2) (NMux (AVar "is1") (AVar "pick12") (AVar "pick10"))
        , NBind "s_next" (bv 2) (NMux (AVar "is0") (AVar "pick10") (AVar "s_inner"))
        , NBind "hit_inner" TBool (NMux (AVar "is1") (ALit (VBool False)) (AVar "b"))
        , NBind "o_hit" TBool (NMux (AVar "is0") (ALit (VBool False)) (AVar "hit_inner"))
        ]
    , nmCertificate = testCertificate "Detector.detector_correct"
    }

detectorNetlist :: Module
detectorNetlist =
  Module
    { modName = Ident "detector"
